def esc(t):
    t = t.replace('"', "'")
    return re.sub(r'([。，？！：])(?=.)', r'\1<br>', t)


def diagram(s, ci, ch):
    p = f"c{ci}"
    L = ["```mermaid", "flowchart TD"]
    first = ch["nodes"][0][1]
    if isinstance(ch["entry"], str):
        L.append(f'  {p}E(["{esc(ch["entry"])}"]) --> {p}{first}')
    else:
        starts = ch.get("starts", {})
        for k, t in enumerate(TH):
            L.append(f'  {p}E{k}(["入口・{t}<br>{esc(ch["entry"][t])}"]) --> {p}{starts.get(t, first)}')
    for n in ch["nodes"]:
        kind, nid = n[0], n[1]
        q = f"{p}{nid}"
        if kind in "mg":
            tag = "關口・" if kind == "g" else ""
            L.append(f'  {q}["{tag}{n[2]}<br>{esc(n[3])}"]')
            nx = n[4]
        elif kind == "x":
            L.append(f'  {q}{{{{"迷霧格<br>{esc(n[2])}"}}}}')
            nx = n[3]
        elif kind == "p":
            L.append(f'  {q}{{"◇ {esc(n[2])}"}}')
            nx = n[3]
        elif kind == "f":
            L.append(f'  {q}{{"◆ 轉折"}}')
            for t in TH:
                L.append(f'  {q} -- {t} --> {p}{n[2][t]}')
            continue
        elif kind == "o":
            tail = "<br>→ 結局" if ci == 2 else ""
            L.append(f'  {q}(["出口<br>{esc(n[2])}{tail}"])')
            continue
        for t in nx:
            L.append(f'  {q} --> {p}{t}')
    L.append("```")
    return "\n".join(L)


