# -*- coding: utf-8 -*-
"""Writes web/public/assets/rules-v5.js (the in-game Rulebook drawer) from docs/rules/zh-TW/V5/Rulebook.md and its
English edition, docs/rules/en/Rulebook.md, and the Player Aids (docs/rules/*/Player-Aid.md).

    python3 web/tools/build_rules.py
"""
import base64
import json
import os
import re

import markdown

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def slug(value, separator="-"):
    """GitHub-style heading ids, so the rulebook's own table of contents (#1-故事與目標) works in the drawer."""
    value = re.sub(r"[^\w\s-]", "", value.strip().lower())
    return re.sub(r"\s", separator, value)


def icon_src(m):
    svg = open(os.path.join(ROOT, "docs", "rules", "icons", m.group(1) + ".svg"), "rb").read()
    return 'src="data:image/svg+xml;base64,' + base64.b64encode(svg).decode() + '"'


def html_of(*path):
    src = open(os.path.join(ROOT, "docs", "rules", *path), encoding="utf-8").read()
    src = re.sub(r"^> (設計理由|This is the English edition).*?\n\n", "", src, flags=re.S | re.M)   # repository notes are not for players
    src = re.sub(r"```mermaid\n.*?```\n", "", src, flags=re.S)            # the flowchart: the list after it says the same
    # token pictures (docs/rules/icons) go into the page itself, so the drawer needs no extra files
    src = re.sub(r'src="(?:\.\./)+icons/([\w-]+)\.svg"', icon_src, src)
    html = markdown.markdown(src, extensions=["tables", "sane_lists", "toc", "md_in_html"], extension_configs={"toc": {"slugify": slug}})
    return html.replace("<img ", '<img class="tok" ')


js = ("// Generated by web/tools/build_rules.py from docs/rules/zh-TW/V5/Rulebook.md and docs/rules/en/Rulebook.md. Do not edit.\n"
      "export const RULES_HTML = " + json.dumps(html_of("zh-TW", "V5", "Rulebook.md"), ensure_ascii=False) + ";\n"
      "export const RULES_HTML_EN = " + json.dumps(html_of("en", "Rulebook.md"), ensure_ascii=False) + ";\n"
      "export const AID_HTML = " + json.dumps(html_of("zh-TW", "Player-Aid.md"), ensure_ascii=False) + ";\n"
      "export const AID_HTML_EN = " + json.dumps(html_of("en", "Player-Aid.md"), ensure_ascii=False) + ";\n"
      "export const SOLO_HTML = " + json.dumps(html_of("zh-TW", "V5", "Solo-Rulebook.md"), ensure_ascii=False) + ";\n"
      "export const SOLO_HTML_EN = " + json.dumps(html_of("en", "Solo-Rulebook.md"), ensure_ascii=False) + ";\n")
open(os.path.join(ROOT, "web", "public", "assets", "rules-v5.js"), "w", encoding="utf-8").write(js)
print(len(js))
