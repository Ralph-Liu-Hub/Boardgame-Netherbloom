# -*- coding: utf-8 -*-
"""Writes web/public/assets/rules-v5.js (the in-game Rulebook drawer) from docs/rules/zh-TW/V5/Rulebook.md.

    python3 web/tools/build_rules.py
"""
import json
import os
import re

import markdown

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = open(os.path.join(ROOT, "docs", "rules", "zh-TW", "V5", "Rulebook.md"), encoding="utf-8").read()
src = re.sub(r"^> V5 取代.*?\n\n", "", src, flags=re.S | re.M)          # repository notes are not for players
src = re.sub(r"```mermaid\n.*?```\n", "", src, flags=re.S)            # the flowchart: the list after it says the same
def slug(value, separator="-"):
    """GitHub-style heading ids, so the rulebook's own table of contents (#1-故事與目標) works in the drawer."""
    value = re.sub(r"[^\w\s-]", "", value.strip().lower())
    return re.sub(r"\s", separator, value)


html = markdown.markdown(src, extensions=["tables", "sane_lists", "toc"], extension_configs={"toc": {"slugify": slug}})
js = ("// Generated by web/tools/build_rules.py from docs/rules/zh-TW/V5/Rulebook.md. Do not edit.\n"
      "export const RULES_HTML = " + json.dumps(html, ensure_ascii=False) + ";\n")
open(os.path.join(ROOT, "web", "public", "assets", "rules-v5.js"), "w", encoding="utf-8").write(js)
print(len(js))
