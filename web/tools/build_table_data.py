# -*- coding: utf-8 -*-
"""Writes web/public/assets/table-story.js from the simulator's V5 storybook and commission data.

    python3 web/tools/build_table_data.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "simulator"))
from netherbloom.storybook_data import SOULS, OBS, ACC, OBL  # noqa: E402
from netherbloom import cards as C  # noqa: E402

TH = {OBS: 0, ACC: 1, OBL: 2}
SLOT = {"地點": "Place", "人物": "Person", "事蹟": "Deed", "感受": "Feeling"}
PAGE = ["第一章", "第二章", "第三章"]
TAGZ = {C.OBS: "執念", C.ACC: "釋懷"}
SLOTZ = {"Place": "地點", "Person": "人物", "Deed": "事蹟", "Feeling": "感受"}


def node(n):
    k = n[0]
    if k in "mg":
        return {"k": k, "id": n[1], "slot": SLOT[n[2]], "text": n[3], "next": n[4]}
    if k == "x":
        return {"k": k, "id": n[1], "text": n[2], "next": n[3]}
    if k == "p":
        return {"k": k, "id": n[1], "text": n[2], "next": n[3]}
    if k == "f":
        return {"k": k, "id": n[1], "next": {TH[t]: v for t, v in n[2].items()}}
    return {"k": "o", "id": n[1], "text": n[2]}


def entry(e):
    return e if isinstance(e, str) else {TH[t]: v for t, v in e.items()}


def cond_text(k):
    parts = []
    if k["page"] is not None:
        parts.append(PAGE[k["page"]] + "有")
    s = "一段點亮的"
    if k["own"]:
        s += "「專屬記憶」"
    else:
        s += (TAGZ.get(k["tag"], "") + SLOTZ.get(k["slot"], "")) or "記憶"
        if not k["slot"]:
            s += "" if s.endswith("記憶") else "記憶"
    parts.append(s)
    return "".join(parts)


out = {}
for s in SOULS:
    out[s["key"]] = {
        "name": s["name"], "blurb": s["blurb"], "trait": s["trait"], "keymem": s["keymem"],
        "threads": list(s["threads"]),
        "chapters": [{
            "title": ch["title"], "entry": entry(ch["entry"]),
            "starts": {TH[t]: v for t, v in ch.get("starts", {}).items()},
            "nodes": [node(n) for n in ch["nodes"]],
            "fates": [{"river": f[0] == "河", "name": f[1], "omen": f[2], "cond": f[3], "event": f[4],
                       "effects": f[5], "thread": TH[f[6]]} for f in ch["fates"]],
        } for ch in s["chapters"]],
        "endings": {("mix" if k == "交織" else str(TH[k])): {"title": v[0], "text": v[1]} for k, v in s["endings"].items()},
        "fatelines": list(s.get("fatelines") or ()), "keylines": list(s.get("keylines") or ()),
        "hidden": {"title": s["hidden"][0], "conds": s["hidden"][1], "text": s["hidden"][2]} if s.get("hidden") else None,
        "commissions": [{"text": k["text"], "cond": cond_text(k)} for k in C.COMMISSIONS.get(s["key"], [])],
    }

js = ("// Generated by web/tools/build_table_data.py from simulator/netherbloom/storybook_data.py. Do not edit.\n"
      "export const STORY = " + json.dumps(out, ensure_ascii=False) + ";\n"
      "export const PULL = [3, 5, 7];\n")
open(os.path.join(ROOT, "web", "public", "assets", "table-story.js"), "w", encoding="utf-8").write(js)
print("souls", len(out), "bytes", len(js))
