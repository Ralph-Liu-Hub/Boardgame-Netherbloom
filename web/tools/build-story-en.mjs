// Writes web/public/assets/table-story-en.js: the storybook in English, from table-story.js and the translations in
// tools/story-en/<soul>.json (one English line for each distinct Chinese line, in the order they first appear).
//   node web/tools/build-story-en.mjs
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
const here = dirname(fileURLToPath(import.meta.url));
const { STORY } = await import(join(here, "../public/assets/table-story.js"));
const SKIP = new Set(["fatelines", "keylines", "blurb", "threads", "name"]);   // not shown on the table
const CJK = /[一-鿿]/;
const out = {};
for (const soul of Object.keys(STORY)) {
  const order = [];
  const collect = (o, k) => {
    if (SKIP.has(k)) return;
    if (typeof o === "string") { if (CJK.test(o) && !order.includes(o)) order.push(o); }
    else if (o && typeof o === "object") for (const kk in o) collect(o[kk], kk);
  };
  collect(STORY[soul]);
  const en = JSON.parse(readFileSync(join(here, "story-en", soul + ".json"), "utf8"));
  if (en.length !== order.length) throw new Error(`${soul}: ${en.length} English lines for ${order.length} Chinese lines`);
  const map = new Map(order.map((zh, i) => [zh, en[i]]));
  const tr = (o, k) => {
    if (typeof o === "string") return SKIP.has(k) || !CJK.test(o) ? o : map.get(o);
    if (Array.isArray(o)) return o.map(x => tr(x, k));
    if (o && typeof o === "object") return Object.fromEntries(Object.entries(o).map(([kk, v]) => [kk, SKIP.has(kk) ? v : tr(v, kk)]));
    return o;
  };
  out[soul] = tr(STORY[soul]);
}
writeFileSync(join(here, "../public/assets/table-story-en.js"),
  "// Generated by web/tools/build-story-en.mjs from table-story.js and web/tools/story-en/*.json. Do not edit.\nexport const STORY_EN = " + JSON.stringify(out) + ";\n");
console.log("table-story-en.js written");
